/* ---------------------------------------------------------------- config */

#define FRAME_MS         25         /* ~40 fps render tick                  */

#define MAX_SHURIKEN      10         /* how many can be airborne at once     */
#define SHURI_W          15
#define SHURI_H          15
#define SHURI_SPEED       5         /* px per frame                         */

#define MAX_KUNAI         10         /* same pooling as the shuriken         */
#define KUNAI_W          27
#define KUNAI_H          11
#define KUNAI_SPEED       9         /* faster: it is a throw                */

#define SUMMON_FRAMES    10
#define SUMMON_FRAME_MS 120         /* 10 * 120ms = 1.2s of jutsu           */
#define SUMMON_HOLD_MS 1000         /* snake sits on screen this longer */

#define IDLE_TEXT_MS   0        /* blank this long before NINJAPAD      */

#define MAX_HELD          9         /* one slot per key on the pad          */

/* ---------------------------------------------------------------- state  */

typedef struct {
    bool    active;
    int16_t x;
    uint8_t y;
    uint8_t frame;
} shuriken_t;

typedef struct {
    bool    active;
    int16_t x;
    uint8_t y;
    bool    right;
} kunai_t;

static shuriken_t shurikens[MAX_SHURIKEN];
static kunai_t    kunais[MAX_KUNAI];

static bool     summon_active  = false;
static bool     summon_holding = false;
static uint8_t  summon_frame   = 0;
static uint16_t summon_timer   = 0;

static uint16_t frame_timer   = 0;
static uint16_t last_busy_time = 0;
static uint8_t  tick          = 0;

/* Keys currently held, so a held key throws exactly one shuriken. */
static uint16_t held_keys[MAX_HELD];
static uint8_t  held_count = 0;

/* Screen is mounted upside down. The SSD1306 does this in hardware, so
 * pixel coordinates below are still plain top-left origin.              */
oled_rotation_t oled_init_user(oled_rotation_t rotation) {
    return OLED_ROTATION_180;
}

/* ---------------------------------------------------------------- blit   */

/* Draw a packed 1bpp bitmap (row-major, MSB first) at (ox, oy).
 * Set mirror to flip it horizontally - used to point the kunai left.   */
static void blit(const uint8_t *bmp, uint8_t w, uint8_t h,
                 int16_t ox, int16_t oy, bool mirror) {
    uint8_t stride = (w + 7) / 8;

    for (uint8_t row = 0; row < h; row++) {
        int16_t py = oy + row;
        if (py < 0 || py >= OLED_DISPLAY_HEIGHT) continue;

        for (uint8_t col = 0; col < w; col++) {
            int16_t px = ox + col;
            if (px < 0 || px >= OLED_DISPLAY_WIDTH) continue;

            uint8_t sc   = mirror ? (w - 1 - col) : col;
            uint8_t byte = pgm_read_byte(&bmp[row * stride + (sc >> 3)]);

            if (byte & (0x80 >> (sc & 7))) {
                oled_write_pixel((uint8_t)px, (uint8_t)py, true);
            }
        }
    }
}

/* ---------------------------------------------------------------- spawn  */

static void throw_shuriken(void) {
    for (uint8_t i = 0; i < MAX_SHURIKEN; i++) {
        if (shurikens[i].active) continue;

        shurikens[i].active = true;
        shurikens[i].x      = -SHURI_W;
        /* Stagger height by slot so a volley scatters instead of stacking. */
        shurikens[i].y      = 2 + (i % 3) * 7;
        shurikens[i].frame  = 0;
        return;
    }
    /* All slots busy - drop the extra rather than queueing. */
}

static void throw_kunai(bool to_the_right) {
    for (uint8_t i = 0; i < MAX_KUNAI; i++) {
        if (kunais[i].active) continue;

        kunais[i].active = true;
        kunais[i].right  = to_the_right;
        kunais[i].x      = to_the_right ? -KUNAI_W : OLED_DISPLAY_WIDTH;
        kunais[i].y      = 1 + (i % 3) * 10;
        return;
    }
    /* Pool full: let the airborne ones finish rather than resetting one. */
}

static void start_summon(void) {
    summon_active  = true;
    summon_holding = false;
    summon_frame   = 0;
    summon_timer   = timer_read();
}

/* ------------------------------------------------------------ held keys  */

static bool key_is_held(uint16_t kc) {
    for (uint8_t i = 0; i < held_count; i++) {
        if (held_keys[i] == kc) return true;
    }
    return false;
}

static void key_hold_add(uint16_t kc) {
    if (held_count < MAX_HELD) held_keys[held_count++] = kc;
}

static void key_hold_remove(uint16_t kc) {
    for (uint8_t i = 0; i < held_count; i++) {
        if (held_keys[i] == kc) {
            held_keys[i] = held_keys[--held_count];
            return;
        }
    }
}

/* ---------------------------------------------------------------- update */

static bool step_world(void) {
    bool anything = false;

    if (summon_active) {
        if (summon_holding) {
            if (timer_elapsed(summon_timer) >= SUMMON_HOLD_MS) {
                summon_active = false;
            }
        } else if (timer_elapsed(summon_timer) >= SUMMON_FRAME_MS) {
            summon_timer = timer_read();
            if (++summon_frame >= SUMMON_FRAMES) {
                /* Animation done: park on the last frame and linger. */
                summon_frame   = SUMMON_FRAMES - 1;
                summon_holding = true;
                summon_timer   = timer_read();
            }
        }
        if (summon_active) return true;
    }

    for (uint8_t i = 0; i < MAX_SHURIKEN; i++) {
        if (!shurikens[i].active) continue;

        shurikens[i].x += SHURI_SPEED;
        if (tick & 1) {                       /* spin at half the frame rate */
            shurikens[i].frame = (shurikens[i].frame + 1) & 3;
        }
        if (shurikens[i].x >= OLED_DISPLAY_WIDTH) {
            shurikens[i].active = false;
        } else {
            anything = true;
        }
    }

    for (uint8_t i = 0; i < MAX_KUNAI; i++) {
        if (!kunais[i].active) continue;

        kunais[i].x += kunais[i].right ? KUNAI_SPEED : -KUNAI_SPEED;
        if (kunais[i].x >= OLED_DISPLAY_WIDTH || kunais[i].x <= -KUNAI_W) {
            kunais[i].active = false;
        } else {
            anything = true;
        }
    }

    return anything;
}

/* ---------------------------------------------------------------- render */

bool oled_task_user(void) {
    if (timer_elapsed(frame_timer) < FRAME_MS) return false;
    frame_timer = timer_read();
    tick++;

    bool busy = step_world();
    if (busy) last_busy_time = timer_read();

    oled_clear();

    if (summon_active) {
        blit(art_summon[summon_frame], OLED_DISPLAY_WIDTH, OLED_DISPLAY_HEIGHT,
             0, 0, false);
    } else if (busy) {
        for (uint8_t i = 0; i < MAX_SHURIKEN; i++) {
            if (!shurikens[i].active) continue;
            blit(art_shuriken[shurikens[i].frame], SHURI_W, SHURI_H,
                 shurikens[i].x, shurikens[i].y, false);
        }
        for (uint8_t i = 0; i < MAX_KUNAI; i++) {
            if (!kunais[i].active) continue;
            /* Mirror when travelling left so the point leads the throw. */
            blit(art_kunai, KUNAI_W, KUNAI_H,
                 kunais[i].x, kunais[i].y, !kunais[i].right);
        }
    } else if (timer_elapsed(last_busy_time) >= IDLE_TEXT_MS) {
        blit(art_ninjapad, OLED_DISPLAY_WIDTH, OLED_DISPLAY_HEIGHT, 0, 0, false);
    }
    /* else: settled but inside the idle delay - leave the screen blank. */

    return false;
}

/* One shuriken per key press. Holding a key does not keep throwing, but
 * tapping several keys quickly still launches a volley.                */
bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    if (record->event.pressed) {
        if (!key_is_held(keycode)) {
            key_hold_add(keycode);
            throw_shuriken();
        }
    } else {
        key_hold_remove(keycode);
    }
    return true;
}

