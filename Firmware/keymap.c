/* ---------------------------------------------------------------- input  */

bool encoder_update_user(uint8_t index, bool clockwise) {
    /* Encoder A and B are wired such that QMK's "clockwise" is physically
     * counter-clockwise on this board, so invert it once here. If the knob
     * ever reads backwards again, flip this line rather than the branches. */
    bool physical_cw = !clockwise;

    if (physical_cw) {
        tap_code(KC_VOLU);
#ifdef OLED_ENABLE
        throw_kunai(true);          /* left to right */
#endif
    } else {
        tap_code(KC_VOLD);
#ifdef OLED_ENABLE
        throw_kunai(false);         /* right to left */
#endif
    }
    return false;
}

void keyboard_post_init_user(void) {
    debug_enable = true;
    debug_matrix = true;
    gpio_set_pin_input_high(GP3);
}

/* Encoder push button on GP3, active low. Edge-triggered and non-blocking:
 * a wait_ms() here would stall the matrix scan and stutter the animation. */
void matrix_scan_user(void) {
    static bool     btn_down  = false;
    static uint16_t btn_timer = 0;

    bool pressed = !gpio_read_pin(GP3);

    if (pressed && !btn_down && timer_elapsed(btn_timer) > 40) {
        btn_down  = true;
        btn_timer = timer_read();
        tap_code(KC_MUTE);
#ifdef OLED_ENABLE
        start_summon();
#endif
    } else if (!pressed && btn_down) {
        btn_down  = false;
        btn_timer = timer_read();
    }
}
